/**
 * Get all appellate courts (محاكم الاستئناف)
 */
export function getAppellateCourts() {
    return COURT_MAPPINGS.map(c => c.appellateCourt);
}
/**
 * Get primary courts for a specific appellate court
 * Returns empty array if appellate court not found
 */
export function getPrimaryCourts(appellateCourt) {
    const mapping = COURT_MAPPINGS.find(c => c.appellateCourt === appellateCourt);
    return mapping ? mapping.primaryCourts : [];
}
/**
 * Get court mapping as JSON (for API responses)
 */
export function getCourtMappingJson(appellateCourt) {
    const primaryCourts = getPrimaryCourts(appellateCourt);
    if (primaryCourts.length === 0) {
        return {
            error: "محكمة الاستئناف غير صالحة"
        };
    }
    return {
        appeal_court: appellateCourt,
        primary_courts: primaryCourts
    };
}
